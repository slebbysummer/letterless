// Turns data/banned-words-en.txt into a TypeScript module shared by the site and the server.
import { readFileSync, writeFileSync } from 'node:fs';

const entries = readFileSync(new URL('../data/banned-words-en.txt', import.meta.url), 'utf8')
  .split(/\r?\n/).map((l) => l.trim().toLowerCase()).filter(Boolean)
  // Entries with digits, symbols or emoji can never be typed (only letters are allowed), so skip them.
  .filter((l) => /^[a-z' -]+$/.test(l));

const out = `// Generated by scripts/gen-banned.mjs from data/banned-words-en.txt. Do not edit by hand.
export const BANNED_WORDS: readonly string[] = ${JSON.stringify([...new Set(entries)], null, 0).replace(/","/g, '",\n  "')};
`;
writeFileSync(new URL('../supabase/functions/_shared/banned-words.ts', import.meta.url), out);
console.log(`Wrote ${entries.length} banned entries`);
